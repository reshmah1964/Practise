def group_test_results(test_runs):
    grouped = {
        "PASS": [],
        "FAIL": [],
        "SKIP": [],
        "INVALID": []
    }
    for test in test_runs:
        test_name = test["name"]
        status = test["status"]
        result = status.strip().upper()

        if result == "PASS":
            grouped["PASS"].append(test_name)
        elif result == "FAIL":
            grouped["FAIL"].append(test_name)
        elif result == "SKIP":
            grouped["SKIP"].append(test_name)
        else:
            grouped["INVALID"].append(test_name)

    return grouped

print(group_test_results(test_runs))

